'use strict';
const path=require('node:path');
const esbuild=require('esbuild');
const ROOT=path.resolve(__dirname,'..');
function options(write=true){
  return {
    absWorkingDir:ROOT,entryPoints:['scripts/entries/kart-runtime.mjs'],
    outfile:'public/js/engines/kart-runtime.mjs',bundle:true,format:'esm',platform:'browser',
    target:'es2022',minify:true,keepNames:true,write,metafile:true,
    // Vendor files retain their own load/streaming path. Lobby and runtime
    // must also share one physics-init promise and one raw GLB byte cache.
    external:['/vendor/*','../../vendor/*','./kart-physics-loader.mjs','./kart-prefetch.mjs'],
    banner:{js:'// Generated by npm run vendor. Edit the kart engine sources, then rebuild.'},
  };
}
function build(write=true){return esbuild.buildSync(options(write));}
if(require.main===module){const result=build();console.log('kart-runtime: '+result.metafile.outputs['public/js/engines/kart-runtime.mjs'].bytes+' bytes');}
module.exports={build,options};
