'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const read=file=>fs.readFileSync(path.join(__dirname,'../public',file),'utf8');
(async()=>{
 const url=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
 const kit=await import(require('./_kit-url')(url(read('js/util.js'))));
 const empty=kit.hudHtml(),full=kit.hudHtml({round:'Round 10 of 12',phase:'Getting ready',progress:'12 of 12 locked in',timer:10});
 for(const name of ['round','phase','progress','timer'])for(const html of [empty,full])assert(html.includes('gk-hud-'+name),'HUD keeps '+name+' mounted');
 const hud=read('css/game-ui.css'),party=read('css/party-scenes.css'),board=read('css/board-duels.css');
 assert.match(hud,/\.gk-hud\s*\{\s*display: grid; grid-template-columns:/);
 assert.match(hud,/\.gk-hud-phase\s*\{ grid-column: 2; grid-row: 1;/);
 assert.match(party,/justify-self:start; width:max-content; max-width:100%/);
 assert.match(hud,/\.gk-hud-progress\s*\{ grid-column: 3; grid-row: 1;/);
 assert.match(hud,/font-variant-numeric: tabular-nums/);
 assert.doesNotMatch(party,/.gk-hud-timer:empty\s*\{\s*display:\s*none/);
 assert.match(board,/\.bk-player,\.bk-player\.is-turn\s*\{ border-width:var\(--outline-w-lg\)/);
 assert.match(board,/\.bk-final\s*\{ position:fixed;/);
 assert.match(board,/\.bk-stage\s*\{ flex:none;/);
 assert.match(board,/\.bk-actions\[hidden\]\s*\{ display:block!important; visibility:hidden/);
 assert.match(board,/\.bk-actions\s*\{min-height:calc\(var\(--control-h\) \+ var\(--space-32\)\)/);
 assert.match(board,/\.bk-timer.has-timer\[hidden\]/);
 assert.match(read('css/ludo.css'),/\.ld-roll-label\s*\{[^}]*height:2.4em/);
 assert.match(read('css/ludo.css'),/height:var\(--game-viewport-height,100dvh\); min-height:0/);
 assert.match(read('css/ludo.css'),/\.ld-stage\.bk-stage\s*\{[^}]*grid-row:5;[^}]*aspect-ratio:1/);
 assert.match(read('css/ludo.css'),/#gbody \.ld-game \.bk-status\s*\{[^}]*height:calc\(var\(--space-64\) \+ var\(--space-24\)\)/);
 const wyr=read('css/would-you-rather.css');
 assert.doesNotMatch(wyr,/\.wyr-choices:not\(\.is-reveal\) .wyr-result\s*\{ display: none/);
 assert.match(wyr,/grid-template-rows:minmax\(2lh,auto\) var\(--space-40\)/);
 assert(!wyr.includes('.wyr-actions:not(:has(> :not([hidden])))'));
 assert.match(read('js/games/reaction-tap.js'),/pad.querySelector\('\.rt-pad-label'\).textContent = label/);
 assert.match(read('css/reaction-tap.css'),/grid-template-areas:"lights" "target" "label"/);
 assert.match(read('css/reaction-tap.css'),/\.rt-pad::before\s*\{ position:absolute; grid-area:target/);
 assert.match(read('css/twenty-questions.css'),/#tqQWrap\s*\{ height:/);
 assert.match(read('js/games/twenty-questions.js'),/No other questions queued/);
 console.log('LAYOUT_STABILITY_PASS: mounted HUD slots, fixed tracks, constant turn rims, reserved controls/results and question/cabinet slots');
})().catch(error=>{console.error(error);process.exitCode=1;});
